COMMON   /STLMOP/ TLDL, TOPINV, TOPM, TIMTQL, TVECOP, TPRED, TSAVE, COEFF(4), CK, CL, CONV, PFCONV, UPDATE
COMMON   /STLMST/ TIME(24), COUNT(24), NBADMU, NMXRST, DUMMY
COMMON   /STLMUI/ R(5), I(9)
!
R(2) = OLDMU
R(3) = MU
R(4) = SECOND() - TIME(20)
R(5) = TPRED
!
I(1) = CNEGF
I(2) = CPOS
I(3) = ERRNO
I(4) = ITERNO
I(5) = N
I(6) = RFIRST
I(7) = RNEW
I(8) = TCONV
I(9) = X
!
RETURN
END
