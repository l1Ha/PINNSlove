REAL(Kind=WP_Kind) ALTMU, CK, CL, COEFF, MU, NEXTMU, OLDMU, R, RDUMP, SECOND, TIME, TIMTQL, TLDL, TOPINV, TOPM, TPRED, TSAVE, TVECOP
INTEGER   CNEG, CNEGF, CONV, COUNT, CPOS, DUMMY, ERRNO, I, IDUMP,  ITERNO, MV, MXNEW, MXOLD, MXRST, N, NBADMU, NIL, NMXRST,   &
                OLCPOS, P, PFCONV, REST, RFIRST, RNEW, ROLD, SCPX,  SOLCPX, TCONV, V, X
LOGICAL   SAFRST, UPDATE, USEMX, ZERBET
COMMON   /STLMCT/ N, ITERNO, TCONV, CNEG, CPOS, OLCPOS, RNEW, ROLD, REST, P, USEMX, ZERBET
COMMON   /STLMER/ RDUMP, ERRNO, IDUMP(2)
COMMON   /STLMFT/ CNEGF, RFIRST, SAFRST
COMMON   /STLMID/ NIL, MV, V, MXNEW, MXOLD, MXRST, SCPX, SOLCPX, X
